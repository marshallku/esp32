#!/usr/bin/env python3
"""Builds the key icons desk-panel draws from the Lucide SVGs in icons.txt.

Each icon is rasterised at SIZE x SIZE with rsvg-convert and kept as its
alpha channel at 4 bits per pixel, two pixels per byte, high nibble first.
The panel tints that coverage with the key's text colour, so only the shape
is stored. Writes, both committed:

    host/desk-core/src/icons/icons.bin   the bitmaps, in NAMES order
    host/desk-core/src/icons/names.rs    the sorted names and the format

Needs rsvg-convert (librsvg) and Pillow. SVGs are cached per Lucide version
under ~/.cache/desk-panel-icons/, so changing LUCIDE fetches fresh ones.
"""

import io
import subprocess
import sys
import urllib.request
from pathlib import Path

from PIL import Image

LUCIDE = "1.49.0"
SIZE = 48
BITS = 4

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "host/desk-core/src/icons"
CACHE = Path.home() / ".cache/desk-panel-icons" / LUCIDE


def names() -> list[str]:
    lines = (line.strip() for line in (HERE / "icons.txt").read_text().splitlines())
    listed = [line for line in lines if line and not line.startswith("#")]
    if len(set(listed)) != len(listed):
        sys.exit("icons.txt lists a name twice")
    return sorted(listed)


def svg(name: str) -> bytes:
    cached = CACHE / f"{name}.svg"
    if not cached.exists():
        url = f"https://unpkg.com/lucide-static@{LUCIDE}/icons/{name}.svg"
        with urllib.request.urlopen(url) as response:
            data = response.read()
        CACHE.mkdir(parents=True, exist_ok=True)
        cached.write_bytes(data)
    return cached.read_bytes()


def bitmap(name: str) -> bytes:
    png = subprocess.run(
        ["rsvg-convert", "--width", str(SIZE), "--height", str(SIZE), "--format", "png"],
        input=svg(name),
        capture_output=True,
        check=True,
    ).stdout
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    levels = [round(a * ((1 << BITS) - 1) / 255) for a in alpha.tobytes()]
    if not any(levels):
        sys.exit(f"{name}: rendered empty")
    return bytes(hi << 4 | lo for hi, lo in zip(levels[0::2], levels[1::2]))


def main() -> None:
    listed = names()
    data = b"".join(bitmap(name) for name in listed)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "icons.bin").write_bytes(data)
    entries = "".join(f'    "{name}",\n' for name in listed)
    (OUT / "names.rs").write_text(
        "// Generated by tools/icons/gen.py from tools/icons/icons.txt; do not edit.\n"
        f"// Lucide {LUCIDE} (ISC licence, https://lucide.dev).\n\n"
        f"pub const SIZE: u16 = {SIZE};\n"
        f"pub const BITS: u8 = {BITS};\n\n"
        "/// Sorted, so a name is found by binary search.\n"
        f"pub const NAMES: [&str; {len(listed)}] = [\n{entries}];\n"
    )
    print(f"{len(listed)} icons, {len(data)} bytes")


if __name__ == "__main__":
    main()
